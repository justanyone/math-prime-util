pub(super) fn max_count(k: u32) -> u64 {
    MAX_COUNTS.get(k as usize).copied().unwrap_or(0)
}
pub(super) fn max_nth(k: u32) -> u64 {
    OFFSETS.get(k as usize).map_or(0, |v| u64::MAX - v)
}
// MPU almost_primes.c: reduce_prime_count_factor.
pub(super) fn reduce_count(mut k: u32, mut n: u64) -> (u32, u64) {
    let mut r = k.saturating_sub(40);
    while (n >> r) < 3_u64.pow(k - r) {
        r += 1;
    }
    k -= r;
    n >>= r;
    (k, n)
}
/// Return an upper bound for the count of integers with `k` prime factors.
///
/// Port of MPU 0.75 `almost_primes.c`, `almost_prime_count_upper` and
/// `_almost_prime_count_bounds`. Prime factors count with multiplicity.
///
/// ```
/// assert_eq!(math_prime_util::almost_prime_count_upper(2, 100), 34);
/// ```
#[must_use]
pub fn almost_prime_count_upper(k: u32, n: u64) -> u64 {
    if k == 2 && n < 256 {
        semiprime_count(n)
    } else {
        bounds(k, n).1
    }
}
#[allow(clippy::too_many_lines)]
pub(super) fn bounds(k: u32, n: u64) -> (u64, u64) {
    if k >= 64 || n >> k == 0 {
        return (0, 0);
    }
    let (k, n) = reduce_count(k, n);
    if k == 0 {
        return (u64::from(n >= 1), u64::from(n >= 1));
    }
    if k == 1 {
        return (prime_count_lower(n), prime_count_upper(n));
    }
    for (limit, value) in [
        (3_u64 << (k - 1), 1),
        (9_u64 << (k - 2), 2),
        (10_u64 << (k - 2), 3),
    ] {
        if n < limit {
            return (value, value);
        }
    }
    let max = max_count(k);
    if n >= max_nth(k) {
        return (max, max);
    }
    let x = n as f64;
    let l = x.ln();
    let ll = l.ln();
    let lp = ll + 0.26153;
    let i = k as usize;
    let (mut ml, mut mu) = if n <= 1048575 {
        (LOWER_20[i], UPPER_20[i])
    } else if n <= 4294967295 {
        (LOWER_32[i], UPPER_32[i])
    } else {
        (LOWER_64[i], UPPER_64[i])
    };
    let (bl, bu) = match k {
        2 => {
            let b = x * (ll + 0.261536) / l;
            if x >= 1e12 {
                ml = 1.0;
                (x * (ll + 0.1769) / l * (1.0 + 0.4232 / l), b)
            } else {
                (b, b)
            }
        }
        3 => {
            ml = if n < 638 {
                0.8418
            } else if n <= 1926 {
                let w = (x - 638.0) / 1288.0;
                (1.0 - w) * 0.8939 + w * 0.9233
            } else if n <= 500194 {
                let w = (x - 1927.0) / 498267.0;
                (1.0 - w) * 0.9233 + w
            } else if n <= 3184393786 {
                let w = (x - 500194.0) / 3183893592.0;
                (1.0 - w) + w * 1.039
            } else {
                1.0004
            };
            if n > 4294967295 {
                mu = 0.8711;
            }
            (
                x * ll * ll / (2.0 * l),
                x * (lp * lp + 1.055852) / (2.0 * l),
            )
        }
        4 => {
            let b = x * lp * lp * lp / (6.0 * l);
            let mut u = b;
            if x > 1e12 {
                u += 0.511977 * x * ((x / 4.0).ln().ln() + 0.261536) / l;
                mu = 1.028;
            }
            if n > 4294967295 {
                mu = 0.780;
            }
            if x > 1e12 {
                mu = 0.6921;
            }
            (b, u)
        }
        _ => {
            let mut b = x / l;
            let logk = f64::from(k).ln();
            let plus = ll + logk * logk.ln() - 0.504377;
            for j in 1..k {
                b *= plus / f64::from(j);
            }
            (b, b)
        }
    };
    let bl = bl * ml;
    let bu = bu * mu;
    (
        if bl >= u64::MAX as f64 || bl > max as f64 {
            max
        } else {
            bl as u64
        },
        if bu >= u64::MAX as f64 || bu > max as f64 {
            max
        } else {
            (bu + 1.0) as u64
        },
    )
}
