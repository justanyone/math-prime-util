/// Estimate the count of semiprimes at most `n`.
///
/// Port of `semi_primes.c`, `semiprime_count_approx`, in MPU 0.75.
/// Use the Crisan and Erban series with the reference truncation tables.
///
/// ```
/// use math_prime_util::semiprime_count_approx;
/// assert_eq!(semiprime_count_approx(100), 34);
/// ```
pub fn semiprime_count_approx(n: u64) -> u64 {
    const SMALL: &[u16] = &[
        0, 4, 6, 9, 10, 14, 15, 21, 22, 25, 26, 33, 34, 35, 38, 39, 46, 49, 51, 55, 57, 58, 62, 65,
        69, 74, 77, 82, 85, 86, 87, 91, 93, 94, 95, 106, 111, 115, 118, 119, 121, 122, 123, 129,
        133, 134, 141, 142, 143, 145, 146, 155, 158, 159, 161, 166, 169, 177, 178, 183, 185, 187,
        194, 201, 202, 203, 205, 206, 209, 213, 214, 215, 217, 218, 219, 221, 226, 235, 237, 247,
        249, 253, 254, 259, 262, 265, 267, 274, 278, 287, 289, 291, 295, 298, 299, 301, 302, 303,
        305, 309, 314, 319, 321, 323, 326, 327, 329, 334, 335, 339, 341, 346, 355, 358, 361, 362,
        365, 371, 377, 381, 382, 386, 391, 393, 394, 395, 398, 403, 407, 411, 413, 415, 417, 422,
        427, 437, 445, 446, 447, 451, 453, 454, 458, 466, 469, 471, 473, 478, 481, 482, 485, 489,
        493, 497, 501, 502, 505, 511, 514, 515, 517, 519, 526, 527, 529, 533, 535, 537, 538, 542,
        543, 545, 551, 553, 554, 559, 562, 565, 566, 573, 579, 581, 583, 586, 589, 591, 597, 611,
        614, 622, 623,
    ];
    const C: [f64; 19] = [
        0.26149721284764277,
        -2.071085062885578,
        -7.6972777412176105,
        -35.345660320564164,
        -206.7150392540651,
        -1511.199787131653,
        -13546.323682845914,
        -146229.10675883567,
        -1867579.628007665,
        -27733045.258413542,
        -470983423.5770329,
        -9011500983.75,
        -191744069149.4,
        -4487573459710.5,
        -114472069580579.8,
        -3158610502077135.5,
        -9.368256778652891e+16,
        -2.97083877025764e+18,
        -1.0027447124006391e+20,
    ];
    const CROSS: [f64; 15] = [
        632.0,
        9385.0,
        136411.0,
        4610076.0,
        66358000.0,
        440590000.0,
        2557200000.0,
        53032001000.0,
        1151076796431.0,
        20416501389724.0,
        165815501587300.0,
        953038830319448.0,
        2.001939613334043e+16,
        1.9255886710925843e+17,
        1.7578838749530324e+18,
    ];
    const MINCOUNT: [f64; 16] = [
        82.0,
        195.0,
        2485.0,
        31446.0,
        906319.0,
        11741185.0,
        72840337.0,
        398702652.0,
        7538564737.0,
        150382042176.0,
        2482510001499.0,
        19204997230933.0,
        106211451717048.0,
        2094735089989940.0,
        1.9282342825922188e+16,
        1.6899648631831514e+17,
    ];
    const MAX_INDEX: u64 = 1_701_748_900_850_019_777;
    if n <= 623 {
        return (SMALL.partition_point(|&v| u64::from(v) <= n) - 1) as u64;
    }
    let logn = (n as f64).ln();
    let loglogn = logn.ln();
    let mut terms = 3;
    while terms <= 17 && n as f64 >= CROSS[terms - 3] {
        terms += 1;
    }
    let mut series = 0.0;
    let mut den = 1.0;
    let mut factorial = 1.0;
    for (i, &coefficient) in C.iter().take(terms).enumerate() {
        if i > 0 {
            factorial *= i as f64;
        }
        series += factorial * (loglogn / den);
        series += coefficient / den;
        den *= logn;
    }
    let result = ((n as f64 / logn) * series + 0.5) as u64;
    if result >= MAX_INDEX {
        return MAX_INDEX;
    }
    result.max(MINCOUNT[terms - 3] as u64)
}
