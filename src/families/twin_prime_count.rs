// The C table covers decimal multiples from 10^7 through 4*10^18.
pub(super) fn table_skip(mut take: impl FnMut(u64, u64) -> bool) {
    let mut step = 0;
    let mut base = 10_000_000;
    for exp in 0..12 {
        for mult in 1..10 {
            if !take(mult * base, STEPS[step]) {
                return;
            }
            step += 1;
            if exp == 11 && mult == 4 {
                return;
            }
        }
        base *= 10;
    }
}

/// Count twin pairs whose smaller prime is at most `n`.
///
/// Port of `twin_primes.c` (MPU 0.75), `twin_prime_count` and
/// `twin_prime_count_range`, with the same decimal count table.
///
/// ```
/// assert_eq!(math_prime_util::twin_prime_count(100), 8);
/// ```
#[must_use]
pub fn twin_prime_count(n: u64) -> u64 {
    let end = n.min(MAX_TWIN);
    let mut sum = 0;
    let mut begin = 0;
    table_skip(|bound, count| {
        if end < bound {
            return false;
        }
        sum += count;
        begin = bound;
        true
    });
    scan(begin, end, |_| {
        sum += 1;
        true
    });
    sum
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_decimal_table_entries() {
        let mut entries = Vec::new();
        table_skip(|bound, count| {
            entries.push((bound, count));
            true
        });
        assert_eq!(entries.len(), STEPS.len());
        assert_eq!(entries[0], (10_000_000, 58_980));
        assert_eq!(
            entries.last(),
            Some(&(4_000_000_000_000_000_000, 724_291_736_697_048))
        );
        assert!(entries.windows(2).all(|w| w[0].0 < w[1].0));
    }
}
