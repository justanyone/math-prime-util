// Neumaier compensation, as in real.c SUM_ADD.
#[derive(Default)]
struct Sum { value: f64, correction: f64 }
impl Sum {
    fn add(&mut self, x: f64) {
        let t = self.value + x;
        self.correction += if self.value.abs() >= x.abs() {
            (self.value - t) + x
        } else { (x - t) + self.value };
        self.value = t;
    }
    fn total(&self) -> f64 { self.value + self.correction }
}
