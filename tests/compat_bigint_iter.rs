#![cfg(feature = "bigint")]
mod common;
use common::Case;
use math_prime_util::bigint::iter::*;
use num_bigint::BigUint;

const FAMILY: &str = "bigint_iter";
fn big(c: &Case, i: usize) -> BigUint {
    c.arg(i)
}

#[test]
fn every_fixture_row_is_replayed() {
    let mut handled = 0;
    common::each(FAMILY, "fordivisors", |c| {
        c.check(Some(
            &fordivisors(&big(c, 0))
                .unwrap()
                .iter()
                .map(ToString::to_string)
                .collect::<Vec<_>>()
                .join(" "),
        ));
        handled += 1;
    });
    assert_eq!(
        handled, 0,
        "fixtures should be generated by tools/gen_fixtures.pl before replay"
    );
}
