fn naive_lucky(n: u64) -> Vec<u64> {
    let mut v: Vec<u64> = (1..=n).step_by(2).collect();
    let mut i = 1;
    while i < v.len() {
        let step = v[i] as usize;
        if step > v.len() {
            break;
        }
        v = v
            .iter()
            .enumerate()
            .filter(|(j, _)| (j + 1) % step != 0)
            .map(|(_, &x)| x)
            .collect();
        i += 1;
    }
    v
}

