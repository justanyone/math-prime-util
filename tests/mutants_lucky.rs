#[test]
fn count_bounds_golden() {
    for &(n, approx, lower, upper) in COUNT_BOUNDS {
        assert_eq!(lucky_count_approx(n), approx, "approx {n}");
        assert_eq!(lucky_count_lower(n), lower, "lower {n}");
        assert_eq!(lucky_count_upper(n), upper, "upper {n}");
    }
}

#[test]
fn nth_bounds_golden() {
    for &(k, approx, lower, upper) in NTH_BOUNDS {
        assert_eq!(nth_lucky_approx(k), Some(approx), "approx {k}");
        assert_eq!(nth_lucky_lower(k), Some(lower), "lower {k}");
        assert_eq!(nth_lucky_upper(k), Some(upper), "upper {k}");
    }
}

#[test]
fn exact_functions_against_textbook_sieve() {
    let list = naive_lucky(320_000);
    for n in (0..3000u64).chain(239_990..240_010).chain(299_990..300_010) {
        let want = list.iter().filter(|&&x| x <= n).count() as u64;
        assert_eq!(lucky_count(n), want, "count {n}");
        if n < 300 || n % 997 == 0 || n >= 299_990 || n == 240_001 {
            assert_eq!(lucky_numbers(0, n), naive_lucky(n), "numbers {n}");
        }
    }
    for n in [310_000u64, 319_999] {
        let want = list.iter().filter(|&&x| x <= n).count() as u64;
        assert_eq!(lucky_count(n), want, "count {n}");
    }
    let set: std::collections::HashSet<u64> = list.iter().copied().collect();
    for n in (0..320_000u64).step_by(3).chain(319_000..320_000) {
        assert_eq!(is_lucky(n), set.contains(&n), "is_lucky {n}");
    }
    for (k, &v) in list.iter().enumerate().step_by(97) {
        assert_eq!(nth_lucky(k as u64 + 1), Some(v));
    }
}

#[test]
fn small_sieve_every_size_and_block_boundaries() {
    // The block-copy sieve below 240000 is sensitive to the list length.
    for n in 0..2500u64 {
        assert_eq!(lucky_numbers(0, n), naive_lucky(n), "numbers {n}");
    }
    for n in (2500..30_000u64).step_by(31).chain([239_999, 240_000]) {
        assert_eq!(lucky_numbers(0, n), naive_lucky(n), "numbers {n}");
    }
}

#[test]
fn small_sieve_every_n_is_a_prefix_of_the_reference() {
    // Lucky numbers up to n are a prefix of those up to any larger bound.
    let reference = naive_lucky(24_000);
    for n in 2500..24_000u64 {
        let got = lucky_numbers(0, n);
        assert_eq!(got[..], reference[..got.len()], "prefix {n}");
        assert_eq!(got.len(), reference.partition_point(|&x| x <= n), "len {n}");
    }
}

#[test]
fn lucky_numbers_single_point_ranges() {
    assert_eq!(lucky_numbers(7, 7), vec![7]);
    assert_eq!(lucky_numbers(8, 8), Vec::<u64>::new());
    assert_eq!(lucky_numbers(241, 241), vec![241]);
    assert_eq!(lucky_numbers(300_001, 300_001), Vec::<u64>::new());
}

#[test]
fn is_lucky_needs_several_sieve_rounds() {
    // Large n make is_lucky grow its sieve more than once.
    let list = lucky_numbers(0, 3_000_000);
    let set: std::collections::HashSet<u64> = list.iter().copied().collect();
    for &n in list.iter().rev().take(200) {
        assert!(is_lucky(n), "{n}");
    }
    for n in (2_999_000..3_000_000u64).step_by(3) {
        assert_eq!(is_lucky(n), set.contains(&n), "{n}");
    }
    for &n in list.iter().step_by(4001) {
        assert!(is_lucky(n), "{n}");
        assert!(!is_lucky(n + 2) || set.contains(&(n + 2)), "{}", n + 2);
    }
}
