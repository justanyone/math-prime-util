# Fixture family `sieve`: t/11-primes.t, t/12-nextprime.t, t/11-clusters.t, t/11-sumprimes.t.
# Functions: primes (1 and 2 args), next_prime, prev_prime, sieve_range, sieve_prime_cluster,
# sum_primes (1 and 2 args), is_prime. List results are space-joined; an empty list is an empty result.
use strict; use warnings;

sub gen_sieve {
  my $fh = shift;
  my $U = '18446744073709551615';
  my @e = edges();
  my $plist = sub { my $r = @_ == 1 ? primes($_[0]) : primes($_[0], $_[1]); join(' ', map { "$_" } @$r) };

  # ---- t/11-primes.t
  # invalid input (negative); a die becomes ERROR. The >u64 inputs of the t file are left out:
  # primes(5e34) segfaults in this build.
  for my $a ([-4]) {
    emit($fh, 'primes', [@$a], sub { $plist->(@$a) });
  }
  for my $a ([2,-4], [-10,7], [-10,-4]) {
    emit($fh, 'primes', [@$a], sub { $plist->(@$a) });
  }
  emit($fh, 'primes', [0, 3572], sub { $plist->(0, 3572) });
  for my $n (0..20) { emit($fh, 'primes', [$n], sub { $plist->($n) }); }
  for my $n (100, 1000, 1999, 3572, 10000) { emit($fh, 'primes', [$n], sub { $plist->($n) }); }
  for my $r ([3,9],[2,20],[30,70],[70,30],[20,2],[2,2],[3,3],[2,3],[2,5],[3,6],[3,7],[4,8],
             [3088,3164],[3089,3163],[3090,3162],[1,1],[0,0],[0,1],[1,2],[0,2],
             [2010733,2010881],[2010734,2010880],[2010733+1,2010733+148-2],
             [3842610773,3842611109],[3842610774,3842611108],[4294967276,4294967316],
             ['1693182318746371','1693182318747671'],
             ['18446744073709551526',$U],['18446744073709551526','18446744073709551614'],
             ['18446744073709551533','18446744073709551557'],
             [4294967200,4294967400],[4294967296,4294967400],[4294967295,4294967296],
             [4294967279,4294967279],[4294967291,4294967291],
             [9223372036854775700,9223372036854775900],
             [$U,$U],['18446744073709551614',$U],[1000000000,1000000100],
             [474973,838390]) {
    my ($lo,$hi) = @$r;
    next if $hi > 1000000 && $hi - $lo > 5000; # keep lists short
    next if $lo == 474973;
    emit($fh, 'primes', [$lo,$hi], sub { $plist->($lo,$hi) });
  }
  # 27150 primes is too long a list: emit the count of a long range as a separate function
  emit($fh, 'primes_count_in_range', [474973, 838390], sub { scalar @{primes(474973, 838390)} });
  for my $n (@e) {
    emit($fh, 'primes', ["$n"], sub { $plist->("$n") }) if $n <= 1000;
    next if $n > $U;
    emit($fh, 'primes', ["$n", "$n"], sub { $plist->("$n", "$n") });
    my $hi = Math::BigInt->new("$n") + 200; $hi = Math::BigInt->new($U) if $hi > Math::BigInt->new($U);
    emit($fh, 'primes', ["$n", "$hi"], sub { $plist->("$n", "$hi") });
  }

  # sieve_range(n, width, depth)
  my @sr = ([0,1000,40],[0,0,0],[0,1,0],[0,2,1],[0,5,0],[0,5,1],[10,5,0],[1,4,2],[1,5,2],[1,6,3],
            [0,20,2],[0,20,3],[45,10,5],[45,10,7],[100,50,$U],[109485,100,3],[109485,100,5],
            [109485,100,7],[109485,100,11],[109485,100,13],[109485,100,17],[0,65,7],
            [10,5,'18446744073709551617'],
            [10,'18446744073709551617',1]);
  for my $a (@sr) {
    emit($fh, 'sieve_range', [@$a], sub { join(' ', map { "$_" } &sieve_range(@$a)) });
  }
  for my $a ([4294967290,100,7],[4294967290,100,13],['18446744073709551515',100,11],
             ['18446744073709551515',100,$U],[1000000,200,23],[1000000007,150,5]) {
    emit($fh, 'sieve_range', [@$a], sub { join(' ', map { "$_" } &sieve_range(@$a)) });
  }

  # ---- t/12-nextprime.t
  for my $n (0..3572) {
    emit($fh, 'next_prime', [$n], sub { next_prime($n) });
    emit($fh, 'prev_prime', [$n], sub { prev_prime($n) });
  }
  for my $n (19609, 360653, 2010733) {
    emit($fh, 'next_prime', [$n], sub { next_prime($n) });
  }
  for my $n (19661, 360653+96, 2010881, 19662, 19660, 19610) {
    emit($fh, 'prev_prime', [$n], sub { prev_prime($n) });
  }
  for my $n (19608, 19610, 19660, 10019, 1234567890) { emit($fh, 'next_prime', [$n], sub { next_prime($n) }); }
  for my $n (2010733 .. 2010880) { emit($fh, 'next_prime', [$n], sub { next_prime($n) }); }
  for my $n (2010734 .. 2010881) { emit($fh, 'prev_prime', [$n], sub { prev_prime($n) }); }
  for my $n (@e, qw/4294967291 4294967310 4294967311 4294967312 4294967278 4294967279 4294967280
                    9223372036854775783 9223372036854775784 9223372036854775807
                    18446744073709551557 18446744073709551556 18446744073709551558
                    18446744073709551611 18446744073709551600 18446744073709551614
                    18446744073709551615 1099511627689 1099511627791 1125899906842597
                    1125899906842598 1125899906842623 1125899906842624 281474976710597/) {
    emit($fh, 'next_prime', ["$n"], sub { u64_or_undef(next_prime("$n")) });
    emit($fh, 'prev_prime', ["$n"], sub { prev_prime("$n") });
  }

  # ---- t/11-clusters.t  (args: lo hi offsets...)
  my @cl = ([0,200,0,2],[317321,319727,0,2,6],[557857,560293,0,4,6],[1,1e9,2,4],[1,1e9,2,8,14,26],
            [0,50,2],[20000,0,2,6,8],[0,30,0]);
  my @patterns = ([0,2,6],[0,2,6,8],[0,2,6,8,12],[0,4,6,10,12],[0,4,6,10,12,16],[0,2,8,12,14,18,20],
                  [0,2,6,8,12,18,20],[0,4,6]);
  push @cl, map { [0,100000,@$_] } @patterns;
  push @cl, [0,20000,2];
  push @cl, [0,30,0,0,2], [0,30,2,0];     # errors
  push @cl, [0,10000,0], [0,1000,2,6], [0,1000,6,12], [0,1000,4], [0,1000,6], [0,1000,12,18], [10,10,2];
  # windows around known large clusters (+-1000, as in the non-GMP path of the test)
  for my $h (['999961920817',[4,6,10,12,16]],['999999217031',[2,6,8,12]],['999998356957',[4,6,10,12]],
             ['9999956467211',[2,6,8,12,18,20]],['9996858589169',[2,8,12,14,18,20]],
             ['99996813484481',[2,6,8,12,18,20,26]],['99997194198047',[2,6,12,14,20,24,26]],
             ['99996215495153',[6,8,14,18,20,24,26]],['999897629673401',[2,6,8,12,18,20,26,30]],
             ['506946970236647',[2,6,12,14,20,24,26,30]],['291985604331973',[4,6,10,16,18,24,28,30]],
             ['999823346788939',[4,10,12,18,22,24,28,30]],['29997979809623711',[2,6,8,12,18,20,26,30,32]],
             ['29998892234668517',[2,6,12,14,20,24,26,30,32]],['9996248338169127877',[6,10,12,16,22,24,30,34,36,40,42]],
             ['2830868185774228331',[2,6,8,12,18,20,26,30,32,36,42]],['999955337060684083',[4,6,10,16,18,24,28,30,34,36]],
             ['999930334493085881',[2,6,8,12,18,20,26,30,32,36]]) {
    my ($n,$p) = @$h;
    my ($lo,$hi) = ($n - 1000, $n + 1000);
    push @cl, [$lo, $hi, @$p];
  }
  push @cl, ['18446744073709551000', $U, 2], ['18446744073709551000', $U, 0, 2, 6], [4294967000, 4294967400, 2],
            [4294967000, 4294967400, 0, 4];
  for my $a (@cl) {
    emit($fh, 'sieve_prime_cluster', [@$a], sub { join(' ', map { "$_" } &sieve_prime_cluster(map { "$_" } @$a)) });
  }

  # ---- t/11-sumprimes.t
  my %sums = ("189695660 to 189695892" => 0, "0 to 300000" => 3709507114, "12345 to 54321" => 132980191,
              "10000000 to 10001000" => 610034659, "1960000 to 2000050" => 5445653916);
  for my $k (sort keys %sums) {
    my ($lo,$hi) = $k =~ /(\d+) to (\d+)/;
    emit($fh, 'sum_primes', [$lo,$hi], sub { u64_or_undef(sum_primes($lo,$hi)) });
  }
  for my $n (0..1000) { emit($fh, 'sum_primes', [$n], sub { u64_or_undef(sum_primes($n)) }); }
  for my $n (qw/100 1000 10000 65535 65536 65537 321059 321060 321072 321073 1000000 10000000 100000000
                1000000000 2000000000 4000000000 4294967295 4294967296 5000000000 10000000000
                19505444491 20705000000 29505444490 29505444491/) {
    emit($fh, 'sum_primes', [0,$n], sub { u64_or_undef(sum_primes(0,$n)) });
    emit($fh, 'sum_primes', [$n], sub { u64_or_undef(sum_primes($n)) });
  }
  my $maxprime = '18446744073709551557';
  emit($fh, 'sum_primes', [$maxprime, '18446744073709551600'], sub { u64_or_undef(sum_primes($maxprime, '18446744073709551600')) });
  emit($fh, 'sum_primes', ['18446744073709551558', $U], sub { u64_or_undef(sum_primes('18446744073709551558', $U)) });
  for my $r ([10,2],[0,0],[1,1],[2,2],[2,3],[4,4],[100,50],[4294967290,4294967300],
             [9223372036854775800,9223372036854776000],['18446744073709551000',$U]) {
    emit($fh, 'sum_primes', [@$r], sub { u64_or_undef((@$r == 1 ? sum_primes($r->[0]) : sum_primes($r->[0], $r->[1]))) });
  }

  # ---- is_prime over small integers and edges
  for my $n (0..999) { emit($fh, 'is_prime', [$n], sub { is_prime($n) ? 1 : 0 }); }
  for my $n (@e, qw/4294967291 4294967297 4294967311 18446744073709551557 18446744073709551533
                    9223372036854775783 1000003 2305843009213693951 18446744073709551556/) {
    emit($fh, 'is_prime', ["$n"], sub { is_prime("$n") ? 1 : 0 });
  }
}
1;
