#!/usr/bin/env perl
# Generates oracle fixtures from Math::Prime::Util for the Rust compat tests.
#
#   . tools/perl-env.sh                   # bootstraps .perl-local/ with MPU 0.75 when missing
#   perl tools/gen_fixtures.pl            # writes every family
#   perl tools/gen_fixtures.pl int sieve  # named families
#
# One family = one file tools/fixtures/<family>.pl that defines `sub gen_<family> { my ($fh) = @_; ... }`
# and writes tests/fixtures/<family>.tsv, one case per line:
#   <function> TAB <space-separated args> TAB <result>
# where <result> is the decimal value, "undef", or "ERROR" (MPU died).
# Multi-value results are space-separated. Lines starting with # are comments.
#
# The fixture is the compatibility spec: the Rust tests never call Perl.
# Workers run offline: generate and commit the fixture BEFORE a port row starts.
use strict;
use warnings;
use FindBin;
use Math::Prime::Util qw/:all/;
use Math::BigInt;

my $out = "$FindBin::Bin/../tests/fixtures";
my $dir = "$FindBin::Bin/fixtures";
my %families;
for my $file (sort glob("$dir/*.pl")) {
  my ($name) = $file =~ m{/([a-z0-9_]+)\.pl$} or next;
  do $file or die "$file: " . ($@ || $!);
  my $gen = __PACKAGE__->can("gen_$name") or die "$file defines no sub gen_$name";
  $families{$name} = $gen;
}
my @want = @ARGV ? @ARGV : sort keys %families;

for my $f (@want) {
  die "unknown family $f (no tools/fixtures/$f.pl)\n" unless $families{$f};
  open my $fh, '>', "$out/$f.tsv" or die "$out/$f.tsv: $!";
  print $fh "# generated by tools/gen_fixtures.pl from Math::Prime::Util $Math::Prime::Util::VERSION; do not edit\n";
  $families{$f}->($fh);
  close $fh;
  print "wrote tests/fixtures/$f.tsv\n";
}

# Helpers shared by every family file.

# emit($fh, 'fn', [args], sub { ... }): one line; a die becomes ERROR, undef stays undef, a list is space-joined.
sub emit {
  my ($fh, $fn, $args, $code) = @_;
  my @r = eval { $code->() };
  my $res = $@ ? 'ERROR' : (!@r || !defined $r[0]) ? 'undef' : join(' ', map { "$_" } @r);
  print $fh join("\t", $fn, join(' ', @$args), $res), "\n";
}

# u64 edge values every family should probe (Math::BigInt objects: stringify with "$_").
sub edges {
  my @e = (0, 1, 2, 3, 4, 5, 7, 8, 9, 15, 16, 17, 31, 32, 33, 63, 64, 65, 100, 255, 256, 257,
           1023, 1024, 1025, 65535, 65536, 65537, 1000003, 2147483647, 2147483648, 4294967295,
           4294967296, 4294967297, 1099511627776, 1125899906842624, 4611686018427387904,
           9223372036854775807, 9223372036854775808, 18446744073709551614, 18446744073709551615);
  return map { Math::BigInt->new("$_") } @e;
}

# u64_or_undef($v): "$v" when it fits in a u64, else 'undef' (for MPU results that overflow into bigints).
sub u64_or_undef {
  my $v = shift;
  return 'undef' unless defined $v;
  return (Math::BigInt->new("$v") > Math::BigInt->new('18446744073709551615')) ? 'undef' : "$v";
}
