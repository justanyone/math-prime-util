#!/usr/bin/env perl
# Generates oracle fixtures from Math::Prime::Util for the Rust compat tests.
#
#   . tools/perl-env.sh
#   perl tools/gen_fixtures.pl            # writes every family
#   perl tools/gen_fixtures.pl int        # one family
#
# Output: tests/fixtures/<family>.tsv, one case per line:
#   <function> TAB <space-separated args> TAB <result>
# where <result> is the decimal value, "undef", or "ERROR" (MPU died).
# Multi-value results are space-separated. Lines starting with # are comments.
#
# The fixture is the compatibility spec: the Rust tests never call Perl.
use strict;
use warnings;
use FindBin;
use Math::Prime::Util qw/:all/;
use Math::BigInt;

my $out = "$FindBin::Bin/../tests/fixtures";
my %families = (
  int => \&gen_int,
);
my @want = @ARGV ? @ARGV : sort keys %families;

for my $f (@want) {
  die "unknown family $f\n" unless $families{$f};
  open my $fh, '>', "$out/$f.tsv" or die "$out/$f.tsv: $!";
  print $fh "# generated by tools/gen_fixtures.pl from Math::Prime::Util $Math::Prime::Util::VERSION; do not edit\n";
  $families{$f}->($fh);
  close $fh;
  print "wrote $out/$f.tsv\n";
}

sub emit {
  my ($fh, $fn, $args, $code) = @_;
  my @r = eval { $code->() };
  my $res = $@ ? 'ERROR' : (!@r || !defined $r[0]) ? 'undef' : join(' ', map { "$_" } @r);
  print $fh join("\t", $fn, join(' ', @$args), $res), "\n";
}

# u64 edge values every family should probe.
sub edges {
  my @e = (0, 1, 2, 3, 4, 5, 7, 8, 9, 15, 16, 17, 31, 32, 33, 63, 64, 65, 100, 255, 256, 257,
           1023, 1024, 1025, 65535, 65536, 65537, 1000003, 2147483647, 2147483648, 4294967295,
           4294967296, 4294967297, 1099511627776, 1125899906842624, 4611686018427387904,
           9223372036854775807, 9223372036854775808, 18446744073709551614, 18446744073709551615);
  return map { Math::BigInt->new("$_") } @e;
}

